#!/usr/bin/env python3
# Debug warp list for the Liquid Crystal build: every map with wild encounters, at a tall-grass / water /
# floor tile, read straight from the ROM (map groups, layouts, tilesets, wild encounter headers).
import struct, sys
rom = open(sys.argv[1], 'rb').read()
out = sys.argv[2]
WILD = int(sys.argv[3], 16) if len(sys.argv) > 3 else 0x08C10200
MAPGROUPS = 0x083526A8
def u32(a): return struct.unpack_from('<I', rom, a & 0x1FFFFFF)[0]
def u16(a): return struct.unpack_from('<H', rom, a & 0x1FFFFFF)[0]
def u8(a): return rom[a & 0x1FFFFFF]
def ok(p): return 0x08000000 <= p < 0x09000000
def behavior(layout, metatile):
    prim, sec = u32(layout + 16), u32(layout + 20)
    ts, idx = (prim, metatile) if metatile < 640 else (sec, metatile - 640)
    if not ok(ts): return None
    attrs = u32(ts + 20)
    if not ok(attrs): return None
    return u32(attrs + idx * 4) & 0x1FF
entries = []
i = 0
while True:
    h = WILD + i * 20
    g, n = u8(h), u8(h + 1)
    if g == 0xFF: break
    land, water, rock, fish = u32(h + 4), u32(h + 8), u32(h + 12), u32(h + 16)
    i += 1
    grp = u32(MAPGROUPS + g * 4)
    if not ok(grp): continue
    hdr = u32(grp + n * 4)
    if not ok(hdr): continue
    lay = u32(hdr)
    if not ok(lay): continue
    w, hgt, data = u32(lay), u32(lay + 4), u32(lay + 12)
    if not (0 < w < 256 and 0 < hgt < 256 and ok(data)): continue
    best = None
    want = (0x02,) if land else ((0x10, 0x11, 0x12, 0x15) if water else ())
    cands = []
    for y in range(hgt):
        for x in range(w):
            b = u16(data + (y * w + x) * 2)
            mt, coll = b & 0x3FF, (b >> 10) & 3
            beh = behavior(lay, mt)
            if beh is None: continue
            if land and coll == 0 and beh == 0x02: cands.append((0, x, y))
            elif coll == 0 and beh == 0 and not land: cands.append((1, x, y))
    if land and not cands:
        for y in range(hgt):
            for x in range(w):
                b = u16(data + (y * w + x) * 2)
                if (b >> 10) & 3 == 0 and behavior(lay, b & 0x3FF) == 0: cands.append((1, x, y))
    if not cands: continue
    cands.sort(key=lambda c: (c[0], abs(c[1] - w // 2) + abs(c[2] - hgt // 2)))
    _, x, y = cands[0]
    entries.append((g, n, x, y, 'land' if land else 'water' if water else 'rock' if rock else 'fish'))
with open(out, 'w') as f:
    f.write('// generated by tools/lc/gen_debug_warps_lc.py (Liquid Crystal maps with wild encounters)\n')
    for g, n, x, y, k in entries:
        f.write('    {%d, %d, %d, %d}, // %s\n' % (g, n, x, y, k))
print(len(entries), 'maps')
