#!/usr/bin/env python3
"""Generate src/data/rt/debug_warps.h for FireRed: every map with wild encounters or trainers,
with a walkable spot near its centre (for the arena review harness)."""
import json, os, struct
R = os.path.join(os.path.dirname(__file__), '..', '..')
layouts = {l['id']: l for l in json.load(open(f'{R}/data/layouts/layouts.json'))['layouts'] if 'id' in l}
wild = set()
for g in json.load(open(f'{R}/src/data/wild_encounters.json'))['wild_encounter_groups']:
    for e in g['encounters']:
        wild.add(e['map'])
out = []
for d in sorted(os.listdir(f'{R}/data/maps')):
    p = f'{R}/data/maps/{d}/map.json'
    if not os.path.exists(p):
        continue
    m = json.load(open(p))
    trainers = any(o.get('trainer_type', 'TRAINER_TYPE_NONE') not in ('TRAINER_TYPE_NONE', 0, '0')
                   for o in m.get('object_events', []) if isinstance(o, dict))
    league = d.startswith('PokemonLeague_') and d.endswith('Room')
    if m['id'] not in wild and not trainers and not league:
        continue
    lay = layouts.get(m['layout'])
    if not lay:
        continue
    w, h = lay['width'], lay['height']
    data = open(f"{R}/{lay['blockdata_filepath']}", 'rb').read()
    grid = struct.unpack('<%dH' % (w * h), data[:w * h * 2])
    cx, cy = w // 2, h // 2
    best = None
    for y in range(1, h - 1):
        for x in range(1, w - 1):
            v = grid[y * w + x]
            if (v >> 10) & 3:
                continue
            elev = v >> 12
            if elev not in (3, 4):
                continue
            # a 3x3 open patch
            ok = all(((grid[(y + j) * w + x + i] >> 10) & 3) == 0 for j in (-1, 0, 1) for i in (-1, 0, 1))
            if not ok:
                continue
            dist = (x - cx) ** 2 + (y - cy) ** 2
            if best is None or dist < best[0]:
                best = (dist, x, y)
    if best is None:
        continue
    out.append('    {MAP_GROUP(%s), MAP_NUM(%s), %d, %d},' % (m['id'], m['id'], best[1], best[2]))
open(f'{R}/src/data/rt/debug_warps.h', 'w').write('// generated by tools/rt/gen_debug_warps.py: every map with wild encounters or trainers (arena review)\n' + '\n'.join(out) + '\n')
print(len(out))
