// Compatibility layer: the real-time engine was written against vanilla Gen 3 move data
// (effect numbers, flags, targets). The Platinum demake is built on pokeemerald-expansion, so
// the engine keeps its own table of "legacy" move data (RtMoveData), filled at battle start:
// Gen 3 moves use the vanilla values, newer moves are translated from gMovesInfo.

#define RT_MOVES_COUNT 468 // all moves up to Gen 4

struct RtMoveData
{
    u8 effect;
    u8 power;
    u8 type;
    u8 accuracy;
    u8 pp;
    u8 secondaryEffectChance;
    u8 target;
    s8 priority;
    u8 flags;
};

#define RT_TARGET_FOES_AND_ALLY 0x20

#define FLAG_MAKES_CONTACT          (1 << 0)
#define FLAG_PROTECT_AFFECTED       (1 << 1)
#define FLAG_MAGIC_COAT_AFFECTED    (1 << 2)
#define FLAG_SNATCH_AFFECTED        (1 << 3)
#define FLAG_MIRROR_MOVE_AFFECTED   (1 << 4)
#define FLAG_KINGS_ROCK_AFFECTED    (1 << 5)

extern struct RtMoveData gRtMoves[RT_MOVES_COUNT];
void RtMoves_Init(void);

// safe accessor: moves beyond the table behave like MOVE_NONE
#define RTM(m) (gRtMoves[(m) < RT_MOVES_COUNT ? (m) : 0])

// true when the move uses ATK/DEF (Gen 4 per-move split)
bool8 RtMove_IsPhysicalMove(u16 move);

